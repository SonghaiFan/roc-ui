async (page) => {
  const checks = [], errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const assert = (ok, message) => { if (!ok) throw Error(message); checks.push(message); };
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto("http://127.0.0.1:4190/");
  const frame = await (await page.locator("iframe").elementHandle()).contentFrame();
  await frame.locator("#tabs").waitFor();
  assert(await page.locator("aside.design-controls").count() === 0, "Appearance sidebar is removed");
  assert(await page.locator(".preset-switch [role=radio]").count() === 3, "Header has three appearance presets");
  const editor = frame.getByLabel("Tabs draft"), original = await editor.elementHandle();
  await editor.fill("A draft retained across all presets");
  await page.getByRole("radio", { name: "Paper", exact: true }).click();
  await frame.waitForFunction(() => getComputedStyle(document.documentElement).getPropertyValue("--roc-paper").trim() === "#fcfbf7");
  assert(await original.evaluate(node => node.isConnected && node.value === "A draft retained across all presets"), "Paper preset retains the original editor and draft");
  await page.getByRole("radio", { name: "Compact", exact: true }).click();
  await frame.locator('.preview-canvas[data-density="compact"]').waitFor();
  assert(await original.evaluate(node => node.isConnected), "Compact preset retains the component tree");
  const fade = frame.locator("#fade");
  assert(await fade.locator(".component-heading").getByRole("button", { name: "Play fade example" }).count() === 1, "Play lives in the preview card header");
  assert(await fade.locator(".component-preview").getByRole("button", { name: "Play fade example" }).count() === 0, "Example body has no duplicate Play control");
  await fade.getByRole("button", { name: "Play fade example" }).click();
  await page.getByRole("radio", { name: "Default", exact: true }).click();
  assert(await fade.getByRole("button", { name: "Reset fade example" }).count() === 1, "Changing presets keeps the example's playback state");
  assert(await fade.getByRole("button", { name: "Fade source and install", exact: true }).count() === 1, "Source and installation share one header action");
  assert(await fade.locator(".component-footer button").count() === 0, "Duplicate download action is removed");
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.locator(".preset-switch").isVisible(), "Three presets remain visible in the mobile header");
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile presets do not overflow the page");
  assert(errors.length === 0, "No browser runtime errors");
  return { passed: checks.length, checks };
}
